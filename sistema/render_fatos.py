#!/usr/bin/env python3
"""
render_fatos.py — generates FATOS.md from fatos.yaml: the document the human reads.

    python3 render_fatos.py            # writes FATOS.md next to the yaml
    python3 render_fatos.py --check    # exits 1 if the FATOS.md on disk differs from the yaml (used by auditar.py)
    python3 render_fatos.py --stdout

Editing the .md by hand loses the edit on the next render. Fix the yaml.
"""
import os
import sys

import fatos as FT

AQUI = os.path.dirname(os.path.abspath(__file__))
SAIDA = os.path.join(AQUI, "FATOS.md")
D = FT.BRUTO


def tabela(cabecalho, linhas):
    out = ["| " + " | ".join(cabecalho) + " |", "|" + "|".join("---" for _ in cabecalho) + "|"]
    out += ["| " + " | ".join(str(c) for c in l) + " |" for l in linhas]
    return "\n".join(out)


def render():
    o = []
    add = o.append
    add("# FATOS\n")
    add("*Generated by `render_fatos.py` from `fatos.yaml`. Do not edit this file: edit the yaml.*\n")
    add("---\n")

    i = D["identidade"]
    add("## 1. Identity\n")
    add(tabela(["Field", "Value"], [
        ("Name on the resume", i["nome_curriculo"]),
        ("Citizenship", i["cidadania_en"]),
        ("Availability", i["disponibilidade_en"]),
        ("Contact", FT.linha_contato()),
        ("Languages (default)", FT.linha_idiomas()),
        ("Education", FT.educacao()),
    ]))
    add("\n---\n")

    add("## 2. Employment dates\n")
    add(tabela(["Company", "Title(s)", "Period"],
               [(e["empresa"], " → ".join(e["cargos"]), f"{FT.mm_aaaa(e['inicio'])} - {FT.mm_aaaa(e['fim'])}")
                for e in D["emprego"].values()]))
    add("\n---\n")

    add("## 3. Approved numbers by company\n")
    for chave, bloco in D.items():
        if chave in D["emprego"] and isinstance(bloco, dict):
            add(f"### {D['emprego'][chave]['empresa']}\n")
            add(tabela(["Field", "Value"], [(k, v) for k, v in bloco.items() if k != "proibido"]))
            if bloco.get("proibido"):
                add("\nNever use: " + "; ".join(f"`{p}`" for p in bloco["proibido"]))
            add("")
    add("---\n")

    if D.get("entregas"):
        add("## 4. Deliverables by company\n")
        for chave, lista in D["entregas"].items():
            add(f"### {D['emprego'][chave]['empresa']} ({FT.periodo(chave)})\n")
            add(tabela(["Id", "Approved sentence", "Number", "When"],
                       [(x["id"], x["frase_en"], x.get("numero", ""), x.get("tempo", "")) for x in lista]))
            add("")
        add("---\n")

    if D.get("anedotas"):
        add("## 5. Work anecdotes\n")
        for a in D["anedotas"]:
            add(f"### {a['id']} ({D['emprego'][a['empresa']]['empresa']}, {a['quando']})\n")
            add(f"- **Situation:** {a['situacao']}")
            add(f"- **Action:** {a['acao']}")
            add(f"- **Result:** {a['resultado']}")
            add(f"- **Use in:** {', '.join(a['usar_em'])}. May name the client: {'yes' if a['pode_citar_cliente'] else 'no'}.\n")
        add("---\n")

    if D.get("clientes"):
        add("## 6. Client facts\n")
        for c in D["clientes"]:
            add(f"### {c['id']}: {c['descricao_publica']}\n")
            add(f"Sector: {c['setor']}. Size: {c['porte']}. May name: {'yes' if c['pode_nomear'] else 'no'}.\n")
            add("\n".join(f"- {f}" for f in c["fatos"]))
            add("\nNever say: " + "; ".join(f"`{n}`" for n in c.get("nunca_dizer", [])) + "\n")
        add("---\n")

    if D.get("banidas"):
        add("## 7. Banned strings\n")
        add(tabela(["Id", "Scope", "Severity", "Why"],
                   [(b["id"], b["escopo"], b["severidade"], b["motivo"]) for b in D["banidas"]]))
        add("\n---\n")

    if D.get("pendencias"):
        add("## 8. Pending items (facts still to confirm)\n")
        for p in D["pendencias"]:
            add(f"- **{p['id']}**: {' '.join(p['texto'].split())}")
        add("")
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    texto = render()
    if "--stdout" in sys.argv:
        print(texto)
    elif "--check" in sys.argv:
        atual = open(SAIDA, encoding="utf-8").read() if os.path.exists(SAIDA) else ""
        sys.exit(0 if atual == texto else 1)
    else:
        with open(SAIDA, "w", encoding="utf-8") as f:
            f.write(texto)
        print("written", SAIDA)
